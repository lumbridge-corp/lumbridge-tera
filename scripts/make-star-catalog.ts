// Builds src/engine/data/stars.ts from the Yale Bright Star Catalogue, 5th revised edition
// (Hoffleit & Warren 1991; NASA/ADC and CDS catalogue V/50, public domain).
//
//   curl -LO http://tdc-www.harvard.edu/catalogs/ybsc5.gz && gunzip ybsc5.gz
//   node scripts/make-star-catalog.ts ybsc5 > src/engine/data/stars.ts
//
// Input checked in at generation time: ybsc5 sha256
// 69797549cc1605aad7ff94e9325e29a1661f2a253917faaa056d9bf20b809afd (9110 records, 1704879 bytes).
//
// Output: every star with a position and a V magnitude (9096; the 14 records without one are
// novae/galaxies), packed 6 bytes per star, little endian, sorted brightest first:
//   uint16 RA  (J2000, 0..65535 = 0..360°)
//   int16  Dec (J2000, ±32767 = ±90°)
//   uint8  V magnitude: (V + 2) · 20, 0.05 mag steps (−2 … 10.75)
//   int8   B−V colour index · 50 (0 when the catalogue has none)
// then base64. Decoded by src/engine/stars.ts.
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/make-star-catalog.ts <ybsc5 catalog file>");
  process.exit(1);
}
const lines = readFileSync(file, "latin1").split("\n");
interface Star { ra: number; dec: number; v: number; bv: number }
const stars: Star[] = [];
for (const l of lines) {
  if (l.length < 110) continue;
  const raH = l.slice(75, 77).trim(), vStr = l.slice(102, 107).trim();
  if (!raH || !vStr) continue;
  const ra = (Number(raH) + Number(l.slice(77, 79)) / 60 + Number(l.slice(79, 83)) / 3600) * 15;
  const dec = (l[83] === "-" ? -1 : 1) * (Number(l.slice(84, 86)) + Number(l.slice(86, 88)) / 60 + Number(l.slice(88, 90)) / 3600);
  const v = Number(vStr);
  const bvStr = l.slice(109, 114).trim();
  const bv = bvStr ? Number(bvStr) : 0;
  if (![ra, dec, v, bv].every(Number.isFinite)) continue;
  stars.push({ ra, dec, v, bv });
}
stars.sort((a, b) => a.v - b.v);
const buf = Buffer.alloc(stars.length * 6);
stars.forEach((s, i) => {
  const o = i * 6;
  buf.writeUInt16LE(Math.round((s.ra / 360) * 65536) % 65536, o);
  buf.writeInt16LE(Math.round((s.dec / 90) * 32767), o + 2);
  buf.writeUInt8(Math.max(0, Math.min(255, Math.round((s.v + 2) * 20))), o + 4);
  buf.writeInt8(Math.max(-127, Math.min(127, Math.round(s.bv * 50))), o + 5);
});
const b64 = buf.toString("base64");
const out = [
  "// GENERATED by scripts/make-star-catalog.ts from the Yale Bright Star Catalogue (BSC5,",
  "// Hoffleit & Warren 1991, NASA/ADC + CDS V/50; public domain). Do not edit by hand.",
  `// ${stars.length} stars, 6 bytes each (RA u16, Dec i16, (V+2)·20 u8, (B−V)·50 i8), brightest first.`,
  `export const STAR_COUNT = ${stars.length};`,
  "export const STARS_B64 =",
  ...b64.match(/.{1,120}/g)!.map((c, i, a) => `  "${c}"${i === a.length - 1 ? ";" : " +"}`),
  "",
];
process.stdout.write(out.join("\n"));
