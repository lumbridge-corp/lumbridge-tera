"""Mock backend: returns tiny valid files instantly, for CI and for development without a GPU."""

from __future__ import annotations

import time

from .. import splat, testassets
from .base import Backend, BackendError, JobContext, Output


class MockBackend(Backend):
    name = "mock"
    kinds = ("image_to_splat", "image_to_model", "text_to_motion")
    license = "Apache-2.0"
    license_url = "https://www.apache.org/licenses/LICENSE-2.0"
    description = "Test data generated by Tera (a splat ball, a cube, a waving arm). No model."

    def run(self, ctx: JobContext) -> list[Output]:
        delay = float(ctx.params.get("mock_delay", 0.2))
        steps = 4
        for i in range(steps):
            ctx.check_cancel()
            time.sleep(delay / steps)
            ctx.set_progress((i + 1) / (steps + 1))
        if ctx.params.get("mock_fail"):
            raise BackendError("mock failure requested (params.mock_fail)")
        out = ctx.out_dir
        if ctx.kind == "image_to_splat":
            cloud = splat.test_cloud(int(ctx.params.get("mock_points", 512)))
            splat.write_spz(out / "splat.spz", cloud)
            splat.write_ply(out / "splat.ply", cloud)
            return [Output(out / "splat.spz", "spz"), Output(out / "splat.ply", "ply")]
        if ctx.kind == "image_to_model":
            (out / "model.glb").write_bytes(testassets.cube_glb())
            return [Output(out / "model.glb", "glb")]
        if ctx.kind == "text_to_motion":
            (out / "motion.bvh").write_text(testassets.wave_bvh())
            return [Output(out / "motion.bvh", "bvh")]
        raise BackendError(f"mock cannot do {ctx.kind}")
